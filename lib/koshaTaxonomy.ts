function classify(text: string, table: { name: string; kw: string[] }[]): string | null {
    const t = text.replace(/\s+/g, "")
    for (const row of table) {
        for (const k of row.kw) {
            if (t.includes(k.replace(/\s+/g, ""))) return row.name
        }
    }
    return null
}

/** 위험 문구 목록 → 재해유형 집계 (많은 순, 상위 n개). 분류 안 되면 '기타'로 모은다. */
export function accidentTypeTop(texts: string[], n = 5): Tally[] {
    return tally(texts, ACCIDENT_TYPES, n)
}

/** 위험 문구 목록 → 기인물 집계 (많은 순, 상위 n개) */
export function agentTop(texts: string[], n = 5): Tally[] {
    return tally(texts, AGENTS, n)
}

function tally(texts: string[], table: { name: string; kw: string[] }[], n: number): Tally[] {
    const m = new Map<string, number>()
    for (const t of texts) {
        const name = classify(t, table) ?? "기타"
        m.set(name, (m.get(name) ?? 0) + 1)
    }
    return [...m.entries()]
        // 같은 건수면 '기타'를 뒤로 — 분류된 항목이 먼저 읽혀야 한다
        .sort((a, b) => b[1] - a[1] || (a[0] === "기타" ? 1 : b[0] === "기타" ? -1 : 0))
        .slice(0, n)
        .map(([name, count]) => ({ name, count }))
}
